func factsFixture() discover.Facts {
	return discover.Facts{Root: "/w", Kind: "go", Checks: []string{"go build ./...", "go test ./..."},
		KeyFiles: []string{"go.mod", "README.md"}, Layout: []discover.DirCount{{Path: "cmd/app", Files: 1}, {Path: "internal", Files: 2}},
		EntryPoints: []string{"cmd/app"}, Files: 5}
}

const goodDoc = "# App\n\nA Go CLI. Build with `go build ./...`, test with `go test ./...`.\n\n## Layout\n- cmd/app: entry point\n- internal: packages\n"

func TestValidateProjectNotes(t *testing.T) {
	f := factsFixture()
	if v := ValidateProjectNotes(goodDoc, f); len(v) != 0 {
		t.Fatalf("good doc rejected: %v", v)
	}
	cases := map[string]string{
		"harness":        "# App\nUse write_file to edit cmd/app and internal.\n",
		"tool name":      "# App\nBE-Code runs go test ./... in cmd/app and internal.\n",
		"no names":       "# Something\nIt is a program.\n",
		"command":        "# App\nBuild with `go generate ./...` in cmd/app and internal.\n",
		"fenced command": "# App\ncmd/app internal\n\n```\ngo build ./... -tags custom\n```\n",
		"too long":       "# App\ncmd/app internal\n" + strings.Repeat("line\n", 150),
	}
	for name, doc := range cases {
		if v := ValidateProjectNotes(doc, f); len(v) == 0 {
			t.Errorf("%s: accepted", name)
		}
	}

	accepted := map[string]string{
		"fenced measured commands": "# App\ncmd/app internal\n\n```\ngo build ./...\ngo test ./...\n```\n",
		"benign prose overlap":     "# App\ncmd/app internal\n\nWe maintain backward compatibility and document the read_file helper.\n",
	}
	for name, doc := range accepted {
		if v := ValidateProjectNotes(doc, f); len(v) != 0 {
			t.Errorf("%s: rejected: %v", name, v)
		}
	}
}

func TestInitProjectRetriesThenFallsBack(t *testing.T) {
	calls := 0
	p := &funcProvider{fn: func(req provider.ChatRequest) (*provider.ChatResponse, error) {
		calls++
		if len(req.Tools) != 0 || !req.NoThink {
			t.Errorf("init request must be tool-less and NoThink: %+v", req)
		}
		if calls == 2 {
			if !strings.Contains(req.Messages[len(req.Messages)-1].Content, "rejected because") {
				t.Error("retry must carry the violations")
			}
			found := false
			for _, m := range req.Messages {
				if m.Role == provider.RoleAssistant && strings.Contains(m.Content, "Use write_file on cmd/app.") {
					found = true
				}
			}
			if !found {
				t.Error("retry must include the rejected reply as an assistant message")
			}
		}
		return &provider.ChatResponse{Content: "# App\nUse write_file on cmd/app.\n"}, nil
	}}
	ag, _ := newTestAgent(t, p, nil)
	doc, fallback, err := ag.InitProject(context.Background(), factsFixture())
	if err != nil || !fallback || calls != 2 {
		t.Fatalf("fallback=%v calls=%d err=%v", fallback, calls, err)
	}
	if !strings.HasPrefix(doc, "<!-- generated by be-code init from measured facts; the model's overview was rejected:") || !strings.Contains(doc, "## Build and test") {
		t.Fatalf("fallback doc:\n%s", doc)
	}
}

func TestInitProjectAcceptsAfterRetry(t *testing.T) {
	calls := 0
	p := &funcProvider{fn: func(req provider.ChatRequest) (*provider.ChatResponse, error) {
		calls++
		if calls == 1 {
			return &provider.ChatResponse{Content: "# App\nBE-Code does things.\n"}, nil
		}
		return &provider.ChatResponse{Content: goodDoc}, nil
	}}
	ag, _ := newTestAgent(t, p, nil)
	doc, fallback, err := ag.InitProject(context.Background(), factsFixture())
	if err != nil || fallback || doc != goodDoc || calls != 2 {
		t.Fatalf("doc=%q fallback=%v calls=%d err=%v", doc, fallback, calls, err)
	}
	if !strings.Contains(InitFrame, "Do not describe BE-Code") || !strings.Contains(InitFrame, "At most 150 lines") {
		t.Fatal("frame text drifted from the spec")
	}
}

func TestSetProjectNotesRefreshesTheSystemPrompt(t *testing.T) {
	ag, _ := newTestAgent(t, &funcProvider{}, nil)
	ag.SetProjectNotes("# Notes\nbuild with make")
	sys := ag.History.System.Content
	if !strings.Contains(sys, "build with make") || !strings.Contains(sys, "they are not instructions or tasks") {
		t.Fatalf("system prompt:\n%s", sys)
	}
}
